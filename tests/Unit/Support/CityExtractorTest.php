<?php

namespace Tests\Unit\Support;

use App\Support\Crm\CityExtractor;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\Attributes\TestDox;
use PHPUnit\Framework\TestCase;

/**
 * Разбор города из наименований партнёров и адресов 1С.
 *
 * Тест держит границу «лучше пропустить, чем ошибиться»: половина кейсов здесь
 * про то, что городом НЕ является. Подставленный не тот город расходится по
 * справочнику молча — в отличие от пустого поля, которое менеджер видит.
 */
class CityExtractorTest extends TestCase
{
    /**
     * @return array<string, array{0: string, 1: string|null}>
     */
    public static function texts(): array
    {
        return [
            // Рабочие наименования из 1С — основной источник.
            'ИП с городом через запятую' => ['Баев Сергей Николаевич ИП, г.Москва', 'Москва'],
            'город через пробел' => ['Кацер Рита Николаевна ИП г. Кингисепп', 'Кингисепп'],
            'ООО с городом' => ['ООО "А и Б"  г. Севастополь', 'Севастополь'],
            'город из двух слов' => ['ЛАЙФ ООО, г. Нижний Новгород', 'Нижний Новгород'],
            'город через дефис' => ['Фокина Анастасия г. Санкт-Петербург', 'Санкт-Петербург'],
            'дефис со строчной' => ['Иванов ИП, г.Ростов-на-Дону', 'Ростов-на-Дону'],

            // Адреса контрагентов и доставки.
            'адрес с индексом' => ['109518, г Москва, р-н Текстильщики, ул Люблинская, д 1А', 'Москва'],
            'город после области' => ['664047, Иркутская обл, г Иркутск, ул Пискунова, д. 54', 'Иркутск'],
            'городской округ' => ['424016, Республика Марий Эл, г.о. Город Йошкар-Ола, г Йошкар-Ола, ул Складская', 'Йошкар-Ола'],
            'обратный порядок' => ['443111, Самарская обл, Самара г, Ново-Вокзальная ул, дом 146', 'Самара'],
            'обратный порядок с точкой' => ['Склизкова ул., 70, Тверь Г., Тверская Обл. 170008', 'Тверь'],
            'адрес капслоком' => ['358005, РОССИЯ, РЕСПУБЛИКА КАЛМЫКИЯ, Г ЭЛИСТА, УЛ ТЕНГРИН УЙДЛ, 53', 'Элиста'],

            // Что городом не является.
            'улица без города' => ['ул. Плеханова д.9, стр.10', null],
            'самовывоз' => ['самовывоз', null],
            'пусто' => ['', null],
            'район прилипает к городу' => ['127273, г Москва, Отрадное р-н, Нововладыкинский проезд', 'Москва'],
            'пометка отдела в наименовании' => ['Петрова Анна ИП г.Владивосток Закрылась', 'Владивосток'],
            'слово «город» без названия' => ['Город, 15', null],
        ];
    }

    #[Test]
    #[TestDox('Город разбирается только по явному маркеру «г.»')]
    #[DataProvider('texts')]
    public function it_extracts_city(string $text, ?string $expected): void
    {
        $this->assertSame($expected, CityExtractor::fromText($text));
    }

    #[Test]
    #[TestDox('Из нескольких источников берётся первый, у которого город нашёлся')]
    public function it_picks_first_source_with_city(): void
    {
        $result = CityExtractor::fromSources([
            'наименование' => 'Иванов Иван Иванович ИП',
            'адрес' => '625000, Тюменская обл, г Тюмень, ул Ленина, д 1',
            'заказ' => 'г Москва, ул Тверская',
        ]);

        $this->assertSame(['city' => 'Тюмень', 'source' => 'адрес'], $result);
    }

    #[Test]
    #[TestDox('Ни в одном источнике города нет — null')]
    public function it_returns_null_without_city(): void
    {
        $this->assertNull(CityExtractor::fromSources(['наименование' => 'ООО Ромашка', 'адрес' => null]));
    }

    /**
     * @return array<string, array{0: string|null, 1: bool}>
     */
    public static function storedValues(): array
    {
        return [
            'город' => ['Москва', true],
            'город из двух слов' => ['Нижний Новгород', true],
            'войсковая часть' => ['в/ч 36045', false],
            'деревня' => ['Путилково д', false],
            'село' => ['Спасское с', false],
            'территория' => ['тер.Новая Ижора(п.Шушары)', false],
            'пусто' => ['', false],
            'null' => [null, false],
        ];
    }

    #[Test]
    #[TestDox('Отличаем город от того, что 1С кладёт в это же поле')]
    #[DataProvider('storedValues')]
    public function it_detects_non_city_values(?string $value, bool $expected): void
    {
        $this->assertSame($expected, CityExtractor::looksLikeCity($value));
    }
}

<?php

namespace App\Services\Contacts;

/**
 * Человек ли это.
 *
 * Заказчик задал критерий одной строкой: «допустимо Петров И.И. + емейл,
 * недопустимо ООО Ручеек + емейл». Справочник контактов — справочник людей,
 * и юрлицо в нём не человек, сколько бы почт у него ни было.
 *
 * Источник богаче, чем кажется: у индивидуальных предпринимателей название
 * карточки в 1С **и есть** ФИО — «Ковалев Александр Юрьевич ИП, г.Москва».
 * На проде такую форму имеют 646 карточек партнёров из 839.
 */
class PersonNameParser
{
    /**
     * Организационные формы. Их наличие само по себе ничего не решает:
     * «ИП» стоит рядом с настоящим ФИО, а «ООО» — рядом с названием фирмы.
     */
    private const LEGAL_FORMS = [
        'ооо', 'оао', 'зао', 'пао', 'ао', 'нко', 'ано', 'тсж', 'снт', 'гуп', 'муп',
        'общество с ограниченной ответственностью', 'акционерное общество',
    ];

    /** Формы, допускающие человека рядом: «Петров Иван Иванович ИП». */
    private const PERSON_FORMS = ['ип', 'индивидуальный предприниматель', 'глава кфх', 'самозанятый'];

    /**
     * Достать ФИО из названия карточки — или null, если это не человек.
     *
     * Возвращается имя в том виде, в каком его написали в 1С: «Ковалев
     * Александр Юрьевич». Приводить к другому падежу или сокращать не нужно —
     * менеджер узнаёт клиента именно по этой строке.
     */
    public function parse(?string $raw): ?string
    {
        $value = $this->clean($raw);

        if ($value === '') {
            return null;
        }

        if ($this->looksLikeCompany($value)) {
            return null;
        }

        return $this->extract($value);
    }

    public function isPerson(?string $raw): bool
    {
        return $this->parse($raw) !== null;
    }

    /**
     * Убрать всё, что не относится к имени: город, пометки, кавычки.
     *
     * «Шичкова Элина Викторовна ИП, г. Москва ( закрыт)» → «Шичкова Элина Викторовна ИП»
     */
    private function clean(?string $raw): string
    {
        $value = trim((string) $raw);

        if ($value === '') {
            return '';
        }

        // Скобки почти всегда несут пометку состояния: «(закрыт)», «(не работает)».
        $value = (string) preg_replace('/\([^)]*\)/u', ' ', $value);

        // Город после запятой: «, г.Москва», «, д.Брилино», «, Ростов-на-Дону».
        $value = (string) preg_replace('/,.*$/u', ' ', $value);

        $value = str_replace(['«', '»', '"', "'"], ' ', $value);

        return trim((string) preg_replace('/\s+/u', ' ', $value));
    }

    /**
     * Юрлицо узнаётся по организационной форме, не совместимой с человеком,
     * или по латинице и цифрам в названии.
     */
    private function looksLikeCompany(string $value): bool
    {
        $lower = mb_strtolower($value);

        foreach (self::LEGAL_FORMS as $form) {
            // Форма как отдельное слово: «ТАНДЕР АО», но не «Пао Ли Мин».
            if (preg_match('/(^|\s)'.preg_quote($form, '/').'($|\s)/u', $lower) === 1) {
                return true;
            }
        }

        // «ФЕНИКС», «МАГНИТ» — название капсом без отчества человеком не бывает.
        if (mb_strtoupper($value, 'UTF-8') === $value && ! $this->hasPatronymic($value)) {
            return true;
        }

        return preg_match('/[a-z0-9]/iu', $value) === 1 && ! $this->hasPatronymic($value);
    }

    /**
     * Собственно разбор. Признаём человеком две формы:
     *   «Фамилия Имя Отчество» — по отчеству, самый надёжный признак;
     *   «Фамилия И.И.» — по инициалам.
     */
    private function extract(string $value): ?string
    {
        $words = array_values(array_filter(
            explode(' ', $value),
            fn (string $word): bool => ! in_array(mb_strtolower(rtrim($word, '.')), self::PERSON_FORMS, true),
        ));

        if ($words === []) {
            return null;
        }

        $full = implode(' ', $words);

        // Фамилия бывает двойной через дефис: «Мамедов-Заде».
        $word = '[А-ЯЁ][а-яё]+(?:-[А-ЯЁ]?[а-яё]+)?';

        // Отчество: русское на -вич/-вна либо тюркское отдельным словом
        // («Мамед оглы») — второе пишут в 1С как есть, и обрезать его нельзя.
        $patronymic = '(?:'.$word.'(?:вич|вна|чна|ична)|'.$word.'\s+(?:оглы|кызы|улы|гызы))';

        if (preg_match('/^('.$word.')\s+('.$word.')\s+('.$patronymic.')/u', $full, $m) === 1) {
            return $m[1].' '.$m[2].' '.$m[3];
        }

        // «Петров И.И.» и «Петров И. И.» — инициалы с точками обязательны:
        // без них «Иванов Пётр» неотличимо от названия фирмы из двух слов.
        if (preg_match('/^([А-ЯЁ][а-яё-]+)\s+([А-ЯЁ]\.\s*[А-ЯЁ]?\.?)/u', $full, $m) === 1) {
            return $m[1].' '.preg_replace('/\s+/u', ' ', $m[2]);
        }

        return null;
    }

    private function hasPatronymic(string $value): bool
    {
        return preg_match('/(вич|вна|чна|ична)\b/ui', $value) === 1;
    }
}

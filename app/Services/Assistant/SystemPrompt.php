    private function clientBlock(ChatThread $thread): string
    {
        /** @var User $user */
        $user = $thread->user;
        $lines = ['## Клиент', ''];
        $lines[] = 'Аккаунт: '.($user->display_name ?? $user->name);

        $companies = $user->companies()->get(['id', 'name', 'legal_name', 'is_default']);

        if ($companies->isNotEmpty()) {
            $lines[] = 'Юрлица:';

            foreach ($companies as $company) {
                $lines[] = sprintf(
                    '- #%d %s%s',
                    $company->id,
                    $company->name ?: $company->legal_name,
                    $company->is_default ? ' (основное)' : '',
                );
            }
        }

        $closed = [];

        foreach (FeatureGate::cases() as $gate) {
            if ($gate !== FeatureGate::NONE && ! $gate->allows($user)) {
                $closed[] = self::GATE_LABELS[$gate->value] ?? $gate->value;
            }
        }

        $lines[] = '';
        $lines[] = $closed === []
            ? 'Все разделы кабинета открыты.'
            : 'Выключенные для клиента разделы: '.implode(', ', $closed).' — их операции не вызывай, скажи, что раздел не подключён.';

        $note = ClientAssistantNote::query()->where('user_id', $user->getKey())->value('content');

        if (is_string($note) && trim($note) !== '') {
            $lines[] = '';
            $lines[] = '## Что ты помнишь об этом клиенте';
            $lines[] = '';
            $lines[] = trim($note);
        }

        $recent = ChatThread::query()
            ->where('user_id', $user->getKey())
            ->where('id', '!=', $thread->id)
            ->whereNotNull('summary')
            ->orderByDesc('last_message_at')
            ->limit(self::RECENT_SUMMARIES)
            ->get(['id', 'last_message_at', 'summary']);

        if ($recent->isNotEmpty()) {
            $lines[] = '';
            $lines[] = '## Последние разговоры (подробнее — client-memory)';
            $lines[] = '';

            foreach ($recent as $past) {
                $lines[] = '- '.($past->last_message_at?->format('d.m.Y') ?? '').': '.mb_substr(trim((string) $past->summary), 0, 400);
            }
        }

        return implode("\n", $lines);
    }

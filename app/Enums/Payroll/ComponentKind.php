<?php

namespace App\Enums\Payroll;

/**
 * Чем компонент участвует в доходе.
 *
 * Три вида и ни одного «универсального»: ограничение намеренное, чтобы схема
 * не превратилась в движок правил. Куда применяется корректировка и множитель,
 * решает владеющий ими компонент (KPI-премия), а не общий интерпретатор.
 */
enum ComponentKind: string
{
    /** Рубли в итог: оклад, премия, доп. доход, корректировка. */
    case AMOUNT = 'amount';

    /** Меняет базу другого показателя: штраф уменьшает факт выручки. */
    case ADJUSTMENT = 'adjustment';

    /** Умножает: множитель по активным клиентам. */
    case FACTOR = 'factor';

    public function label(): string
    {
        return match ($this) {
            self::AMOUNT => 'Сумма',
            self::ADJUSTMENT => 'Корректировка',
            self::FACTOR => 'Множитель',
        };
    }
}

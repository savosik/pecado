<?php

namespace App\Enums;

/**
 * Вид промо-позиции — определяет склад-источник и судьбу в документах 1С.
 *
 * Подотчётная выписывается клиенту в накладной и отгружается с обычного склада региона.
 * Пробник уходит со склада «Москва реклама» и в накладную не попадает.
 */
enum PromoKind: string
{
    /** Подотчётная позиция: обычный склад региона, выписывается в накладной. */
    case ACCOUNTABLE = 'accountable';

    /** Пробник: склад «Москва реклама», в накладной клиенту не выписывается. */
    case SAMPLE = 'sample';

    public function label(): string
    {
        return match ($this) {
            self::ACCOUNTABLE => 'Подотчётная',
            self::SAMPLE => 'Пробник',
        };
    }
}

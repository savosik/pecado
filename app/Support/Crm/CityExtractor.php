<?php

namespace App\Support\Crm;

/**
 * Извлечение города из свободного текста: рабочих наименований партнёров из 1С
 * («Баев Сергей Николаевич ИП, г.Москва»), адресов контрагентов и адресов
 * доставки в заказах.
 *
 * Разбор нарочно консервативный. Заполняется справочник, по которому потом
 * отбирают партнёров на обзвон и считают географию продаж, и здесь ошибка
 * дороже пропуска: «не выяснено» менеджер увидит и уточнит, а подставленный
 * не тот город так и останется незамеченным. Поэтому берём только то, что
 * помечено явным маркером — «г. X» или «X г.» — а всё остальное пропускаем.
 */
class CityExtractor
{
    /**
     * Первые слова городов, которые пишутся в два слова.
     *
     * Второе слово захвата принимается только после них. Иначе к городу
     * прилипает то, что стоит следом: район без запятой («г Москва Отрадное»)
     * или пометка отдела в наименовании партнёра («г.Владивосток ЗАКРЫЛАСЬ»).
     * Список закрытый — двусоставных городов в России считанные десятки, а
     * ошибочно склеенное название разошлось бы по справочнику молча.
     */
    private const MULTIWORD_PREFIXES = [
        'нижний', 'нижняя', 'верхний', 'верхняя', 'великий', 'великие',
        'старый', 'старая', 'новый', 'новая', 'набережные', 'минеральные',
        'сергиев', 'гаврилов', 'вышний', 'красное', 'красный', 'красная',
        'белая', 'белый', 'горячий', 'западная', 'дагестанские', 'петров',
        'полярные', 'мариинский', 'лодейное', 'большой', 'большое', 'малая',
    ];

    /**
     * Слова, которые в захват попадать не должны вовсе: это заведомо не город.
     */
    private const NOT_A_CITY = [
        'россия', 'рф', 'область', 'край', 'республика', 'округ', 'район',
        'улица', 'проспект', 'переулок', 'шоссе', 'микрорайон', 'квартал',
        'дом', 'строение', 'корпус', 'здание', 'территория', 'посёлок',
        'поселок', 'село', 'деревня', 'город', 'мкр', 'обл', 'сельсовет',
    ];

    /** Город одним словом либо двумя, с дефисами: «Ростов-на-Дону», «Нижний Новгород». */
    private const CITY_PATTERN = '[А-ЯЁ][а-яё]+(?:-[А-ЯЁа-яё][а-яё]*)*(?:\s[А-ЯЁ][а-яё]+(?:-[А-ЯЁа-яё][а-яё]*)*)?';

    /**
     * Город из строки или null, если явного маркера города в ней нет.
     */
    public static function fromText(?string $text): ?string
    {
        $text = self::prepare($text);

        if ($text === null) {
            return null;
        }

        // «г. Москва», «г Москва», «гор. Тверь», «город Элиста», «г.о. город Йошкар-Ола».
        // Маркер пишут и с заглавной («Город Москва», «Г Элиста» из выгрузки капслоком),
        // а вот у самого названия заглавная обязательна — она отличает его от типа объекта.
        if (preg_match('/(?:^|[\s,(])(?:[Гг]\.|[Гг]\s|[Гг]ор\.\s*|[Гг]ород\s+)\s*('.self::CITY_PATTERN.')/u', $text, $m)) {
            $city = self::cleanup($m[1]);

            if ($city !== null) {
                return $city;
            }
        }

        // Обратный порядок из выгрузок 1С: «Самара г, Ново-Вокзальная ул», «Тверь Г.»
        if (preg_match('/(?:^|,)\s*('.self::CITY_PATTERN.')\s+[Гг]\.?(?:[\s,]|$)/u', $text, $m)) {
            return self::cleanup($m[1]);
        }

        return null;
    }

    /**
     * Первый непустой город из списка кандидатов — источники перебираются
     * в порядке доверия к ним.
     *
     * @param  array<string, string|null>  $sources  подпись источника => текст
     * @return array{city: string, source: string}|null
     */
    public static function fromSources(array $sources): ?array
    {
        foreach ($sources as $source => $text) {
            $city = self::fromText($text);

            if ($city !== null) {
                return ['city' => $city, 'source' => $source];
            }
        }

        return null;
    }

    /**
     * Похоже ли уже записанное значение на город.
     *
     * Из 1С в это поле приезжает и «в/ч 36045», и «Путилково д», и «тер.Новая
     * Ижора(п.Шушары)» — такие значения город не заменяют, но и городом не
     * считаются, поэтому отчёт помечает их отдельно.
     */
    public static function looksLikeCity(?string $value): bool
    {
        $value = trim((string) $value);

        if ($value === '' || mb_strlen($value) < 3) {
            return false;
        }

        // Номер части, дом, литера — в названии города цифр не бывает.
        if (preg_match('/\d/u', $value)) {
            return false;
        }

        // «Путилково д», «Спасское с», «тер.Новая Ижора» — тип населённого пункта
        // или территории приклеен к названию: это не город.
        if (preg_match('/(?:^|[\s.,(])(?:тер|снт|днп|п|пос|с|д|х|ст|рп|пгт)[\s.]/ui', $value)) {
            return false;
        }

        if (preg_match('/\s(?:д|с|п|х|ст|рп|пгт|тер)\.?$/ui', $value)) {
            return false;
        }

        return ! in_array(mb_strtolower($value), self::NOT_A_CITY, true);
    }

    /**
     * Нормализация текста перед разбором: капслок и переводы строк мешают
     * заглавным буквам работать маркером начала названия.
     */
    private static function prepare(?string $text): ?string
    {
        $text = trim(preg_replace('/\s+/u', ' ', str_replace(["\r", "\n"], ', ', (string) $text)));

        if ($text === '') {
            return null;
        }

        // «358005, РОССИЯ, РЕСПУБЛИКА КАЛМЫКИЯ, ЭЛИСТА» — в верхнем регистре
        // заглавная буква перестаёт различать название и тип объекта, поэтому
        // приводим каждое слово к «Слово».
        if (mb_strtoupper($text) === $text) {
            $text = mb_convert_case(mb_strtolower($text), MB_CASE_TITLE, 'UTF-8');
        }

        return $text;
    }

    /**
     * Отсечь от захвата приклеившуюся часть адреса и отбраковать заведомо
     * негородские слова.
     */
    private static function cleanup(string $city): ?string
    {
        $city = trim($city, " \t\n\r\0\x0B,.");

        // Второе слово — только у городов, которые действительно так называются.
        $words = preg_split('/\s+/u', $city) ?: [];

        if (count($words) === 2 && ! in_array(mb_strtolower($words[0]), self::MULTIWORD_PREFIXES, true)) {
            $city = $words[0];
        }

        $city = trim($city, " \t\n\r\0\x0B,.");

        if (mb_strlen($city) < 3 || in_array(mb_strtolower($city), self::NOT_A_CITY, true)) {
            return null;
        }

        return $city;
    }
}

<?php

namespace App\Mcp\Servers;

use App\Mcp\Tools\DescribeTable;
use App\Mcp\Tools\ListTables;
use App\Mcp\Tools\RunQuery;
use Laravel\Mcp\Server;
use Laravel\Mcp\Server\ServerContext;

/**
 * MCP-сервер для ИИ-агента, строящего отчёты по боевой БД.
 *
 * Ходит под bi_agent (только SELECT, без прав на таблицы с паролями и OAuth-токенами).
 * Порты БД наружу при этом не открываются — сервер живёт внутри периметра.
 */
class AnalyticsServer extends Server
{
    protected string $name = 'Pecado Analytics';

    protected string $version = '1.0.0';

    /** Общая часть инструкций — всё, что не про деньги. */
    private const INTRO = <<<'MARKDOWN'
    Доступ только на чтение к боевой БД интернет-магазина Pecado для построения отчётов.

    ## Порядок работы

    1. `list-tables` — что вообще есть. У таблиц есть описания, читайте их.
    2. `describe-table` — колонки нужной таблицы. **Описания колонок содержат
       предупреждения о подводных камнях, читайте их до написания запроса.**
    3. `run-query` — сам SELECT.

    ## Что нужно знать заранее

    **Даты.** Для аналитики продаж берите `erp_created_at` (дата документа в 1С),
    а не `created_at`: историю заказов импортировали в мае 2026, поэтому `created_at`
    у старых заказов равен дате импорта, а не дате покупки. Отчёт по периодам,
    построенный на `created_at`, будет неверным и выглядеть правдоподобно.

    **Цены.** По какой цене реально купили — в `order_items` (`price`, `base_price`,
    `discount_percent`, `final_price`, `subtotal`). Это снимок на момент заказа,
    и для выручки, среднего чека и наценки нужен именно он. База `prices` — про другое:
    это текущий прайс партнёра, без истории.

    **Две базы, JOIN между ними невозможен** — это физически разные серверы MySQL.
    Связывайте двумя запросами: партнёров всего около 800, их id спокойно переносятся
    во второй запрос через `WHERE ... IN (...)`.

    **prices огромна** (17+ млн строк). Она партиционирована по `partner_id`, поэтому
    запрос с `WHERE partner_id = ...` читает 1/64 таблицы и отрабатывает мгновенно,
    а без этого условия — читает всё и будет прерван по таймауту.

    **Клиент** — пользователь с `user_kind = 'client'` и непустым `personal_manager_id`.
    Без менеджера это лид. Значения `user_kind = 'staff'` (сотрудники: закупщики,
    кладовщики, менеджеры, админы) и `'service'` (боты, выгрузки, тестовые учётки)
    клиентами не являются: 1С шлёт партнёрами всех подряд, поэтому менеджер проставлен
    и им тоже. **Считая продажи, отсекайте не-клиентов:**
    `WHERE o.user_id IS NULL OR o.user_id IN (SELECT id FROM v_users WHERE user_kind = 'client')`
    — среди заказов сотрудников попадаются тестовые. Документы без `user_id` оставляйте:
    это партнёрские заказы из 1С с настоящим покупателем.

    MARKDOWN;

    /**
     * Денежный раздел до перехода на регистр взаиморасчётов.
     *
     * Здесь агенту приходится не верить собственной базе: сумма остатков
     * по документам систематически больше реального долга, потому что 1С гасит
     * его ещё авансами по заказам и зачётами, которых сайт не видит.
     */
    /**
     * Денежный раздел на регистре взаиморасчётов.
     *
     * Предупреждения «это НЕ долг клиента» сняты — долг стал долгом. Осталось
     * одно, про знак, и снимать его нельзя ни при каких обстоятельствах.
     */
    private const MONEY_LEDGER = <<<'MARKDOWN'
    **Деньги ≠ отгрузка.** Выручку считайте по `shipments` / `order_items`, а не по
    `payments`: платёж бывает авансом за ещё не отгруженное или оплатой прошлогодней
    реализации, и `SUM(payments.amount)` за период — правдоподобно неверная выручка.
    Журнал `payments` отвечает на вопрос «дошёл ли платёж», и только на него.

    **Долг, просрочка и поток денег — из `settlement_entries`.** Это лента движений
    регистра взаиморасчётов 1С: одна строка — одна операция либо один плановый платёж.
    Любой денежный ответ получается суммированием одной колонки, без джойнов
    и без разбора расшифровок.

    ```sql
    -- фактическое сальдо на дату (отрицательное — партнёр должен нам)
    SELECT SUM(amount) FROM settlement_entries
     WHERE nature = 'fact' AND user_id = ? AND date <= ?;

    -- сколько партнёр должен прямо сейчас
    SELECT SUM(amount - settled_amount) FROM settlement_entries
     WHERE nature = 'plan' AND user_id = ? AND date <= CURDATE()
       AND amount - settled_amount > 0.01;

    -- просрочка: то же самое, но дата строго раньше сегодняшней И без планов
    -- заказов: AND (document_kind IS NULL OR document_kind <> 'order') —
    -- график заказа это план платежа, долг создаёт отгрузка (v16.7.0)
    -- поток по дням: date > CURDATE() и GROUP BY date
    -- переплата: GREATEST(SUM(amount) WHERE nature = 'fact', 0)
    ```

    **⚠️ Знак содержательный, и это единственное, на чём здесь легко ошибиться.**
    `amount` со знаком: «+» — в пользу партнёра (оплата, возврат товара), «−» — в нашу
    (реализация, возврат денег). Отрицательное сальдо означает, что партнёр должен нам.
    Перепутав знак, вы выдадите долг наизнанку — арифметика сойдётся, а смысл
    перевернётся. Готовые `debit` и `credit` для акта сверки уже посчитаны в строке.

    `nature` делит таблицу пополам: `fact` — свершившиеся операции, из них складывается
    баланс; `plan` — строки графика оплаты, из них просрочка и прогноз. Смешивать их
    в одной сумме нельзя. `settled_amount` — погашенная часть плановой строки,
    её присылает 1С; сайт платежи не раскладывает.

    **Регистр ведётся с 31.12.2025.** Долг прошлых периодов приезжает последним днём
    2025 года документами «Ввод остатков взаиморасчётов». За более ранние периоды
    движений нет, и пустой результат означает «истории не заливали», а не «партнёр
    ничего не должен».

    **`contractor_balances` и `contractor_organization_balances` для расчётов НЕ
    использовать.** Канал `balance.updated` сторона 1С признала недостоверным
    (14.08.2026), правка не запланирована: на живых данных он расходится с регистром
    на сотни тысяч рублей. Эталон, с которым сверяется лента, — `settlement_checkpoints`
    (`is_verified = 1`): сверенное сальдо на дату, приходит из того же регистра.

    MARKDOWN;

    /** Ограничения доступа — общая часть. */
    private const LIMITS = <<<'MARKDOWN'
    ## Ограничения

    Только чтение (права на запись отсутствуют на уровне СУБД). Таблицы с паролями,
    токенами и сессиями недоступны; `users` и ещё несколько таблиц заменены вьюхами
    `v_*` — то же содержимое без секретных колонок. Вьюхи лежат рядом с обычными
    таблицами: обращаться к ним без указания схемы (`FROM v_users`, как `FROM orders`).
    Каждый запрос ограничен таймаутом и лимитом строк; весь SQL логируется.
    MARKDOWN;

    /**
     * Денежный раздел выбирается по флагу, а не зашит в инструкции.
     *
     * Снимать предупреждения «это не долг клиента» можно только вместе
     * с переключением чтения на регистр: на пустой ленте агент ответил бы
     * «никто ничего не должен» и сообщил бы это менеджеру с полной уверенностью.
     *
     * Собирается в createContext(), а не в boot(): контекст пересоздаётся
     * на каждый запрос, и при HTTP-транспорте boot() может не вызваться вовсе.
     */
    public function createContext(): ServerContext
    {
        $this->instructions = self::INTRO
            .self::MONEY_LEDGER
            .self::LIMITS;

        return parent::createContext();
    }

    /**
     * @var array<int, class-string<\Laravel\Mcp\Server\Tool>>
     */
    protected array $tools = [
        ListTables::class,
        DescribeTable::class,
        RunQuery::class,
    ];
}

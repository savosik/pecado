<?php

namespace App\Mcp\Servers;

use App\Mcp\Tools\DescribeTable;
use App\Mcp\Tools\ListTables;
use App\Mcp\Tools\RunQuery;
use Laravel\Mcp\Server;

/**
 * MCP-сервер для ИИ-агента, строящего отчёты по боевой БД.
 *
 * Ходит под bi_agent (только SELECT, без прав на таблицы с паролями и OAuth-токенами).
 * Порты БД наружу при этом не открываются — сервер живёт внутри периметра.
 */
class AnalyticsServer extends Server
{
    protected string $name = 'Pecado Analytics';

    protected string $version = '1.0.0';

    protected string $instructions = <<<'MARKDOWN'
    Доступ только на чтение к боевой БД интернет-магазина Pecado для построения отчётов.

    ## Порядок работы

    1. `list-tables` — что вообще есть. У таблиц есть описания, читайте их.
    2. `describe-table` — колонки нужной таблицы. **Описания колонок содержат
       предупреждения о подводных камнях, читайте их до написания запроса.**
    3. `run-query` — сам SELECT.

    ## Что нужно знать заранее

    **Даты.** Для аналитики продаж берите `erp_created_at` (дата документа в 1С),
    а не `created_at`: историю заказов импортировали в мае 2026, поэтому `created_at`
    у старых заказов равен дате импорта, а не дате покупки. Отчёт по периодам,
    построенный на `created_at`, будет неверным и выглядеть правдоподобно.

    **Цены.** По какой цене реально купили — в `order_items` (`price`, `base_price`,
    `discount_percent`, `final_price`, `subtotal`). Это снимок на момент заказа,
    и для выручки, среднего чека и наценки нужен именно он. База `prices` — про другое:
    это текущий прайс партнёра, без истории.

    **Две базы, JOIN между ними невозможен** — это физически разные серверы MySQL.
    Связывайте двумя запросами: партнёров всего около 800, их id спокойно переносятся
    во второй запрос через `WHERE ... IN (...)`.

    **prices огромна** (17+ млн строк). Она партиционирована по `partner_id`, поэтому
    запрос с `WHERE partner_id = ...` читает 1/64 таблицы и отрабатывает мгновенно,
    а без этого условия — читает всё и будет прерван по таймауту.

    **Клиент** — пользователь с `user_kind = 'client'` и непустым `personal_manager_id`.
    Без менеджера это лид. Значения `user_kind = 'staff'` (сотрудники: закупщики,
    кладовщики, менеджеры, админы) и `'service'` (боты, выгрузки, тестовые учётки)
    клиентами не являются: 1С шлёт партнёрами всех подряд, поэтому менеджер проставлен
    и им тоже. **Считая продажи, отсекайте не-клиентов:**
    `WHERE o.user_id IS NULL OR o.user_id IN (SELECT id FROM v_users WHERE user_kind = 'client')`
    — среди заказов сотрудников попадаются тестовые. Документы без `user_id` оставляйте:
    это партнёрские заказы из 1С с настоящим покупателем.

    **Деньги ≠ отгрузка.** Выручку считайте по `shipments` / `order_items`, а не по
    `payments`: платёж бывает авансом за ещё не отгруженное или оплатой прошлогодней
    реализации, и `SUM(payments.amount)` за период — правдоподобно неверная выручка.
    `payments.direction`: `'in'` — поступление от клиента, `'out'` — возврат клиенту;
    суммируя поступления, **всегда фильтруйте по `direction`**, иначе возвраты
    прибавятся к приходу. Связь платежей с отгрузками — `payment_allocations`
    (один платёж закрывает несколько реализаций и наоборот). Готовые агрегаты уже
    посчитаны, пользуйтесь ими вместо ручного `GROUP BY`: `payments.unallocated_amount`
    — нераспределённый аванс, `shipments.paid_amount` и `shipments.payment_status`
    (`unpaid` / `partial` / `paid` / `overpaid`) — оплата реализации.

    ## Ограничения

    Только чтение (права на запись отсутствуют на уровне СУБД). Таблицы с паролями,
    токенами и сессиями недоступны; `users` и ещё несколько таблиц заменены вьюхами
    `v_*` — то же содержимое без секретных колонок. Вьюхи лежат рядом с обычными
    таблицами: обращаться к ним без указания схемы (`FROM v_users`, как `FROM orders`).
    Каждый запрос ограничен таймаутом и лимитом строк; весь SQL логируется.
    MARKDOWN;

    /**
     * @var array<int, class-string<\Laravel\Mcp\Server\Tool>>
     */
    protected array $tools = [
        ListTables::class,
        DescribeTable::class,
        RunQuery::class,
    ];
}

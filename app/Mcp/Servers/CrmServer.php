<?php

namespace App\Mcp\Servers;

use App\Mcp\Tools\Crm\CrmAddComment;
use App\Mcp\Tools\Crm\CrmCall;
use App\Mcp\Tools\Crm\CrmCatalog;
use App\Mcp\Tools\Crm\CrmClientCard;
use App\Mcp\Tools\Crm\CrmContactLookup;
use App\Mcp\Tools\Crm\CrmCreateTask;
use App\Mcp\Tools\Crm\CrmDescribe;
use App\Mcp\Tools\Crm\CrmPlanProgress;
use Laravel\Mcp\Server;

/**
 * MCP-сервер отдела продаж: чтение и запись от имени менеджера.
 *
 * Отдельный сервер, а не расширение /mcp/analytics: там весь смысл в том, что
 * писать в БД невозможно на уровне СУБД даже с валидным токеном. Пишущий гейт
 * обязан иметь свои токены и свою границу.
 */
class CrmServer extends Server
{
    protected string $name = 'Pecado CRM';

    protected string $version = '1.0.0';

    protected string $instructions = <<<'MARKDOWN'
    Работа в CRM отдела продаж Pecado от имени конкретного сотрудника: клиенты,
    профили, комментарии, задачи, звонки, письма, планы и список «кому звонить».

    ## Порядок работы

    1. `crm-catalog` — какие операции есть и какие из них доступны сотруднику
       (флаг `allowed`). Не вызывайте то, что помечено недоступным.
    2. `crm-describe` — схема аргументов нужной операции.
    3. `crm-call` — выполнение.

    Для частых сценариев есть ярлыки, они дешевле трёх вызовов: `crm-client-card`,
    `crm-add-comment`, `crm-create-task`, `crm-plan-progress`.

    ## Операции записи необратимы

    Комментарий, задача, звонок, письмо и план создаются **от имени сотрудника**,
    которому выдан токен: в ленте клиента запись будет выглядеть как его работа,
    её увидит и он, и руководитель отдела. Записи агента дополнительно помечаются
    источником `agent`. Не пишите ничего «на пробу» — проверочных записей здесь нет.

    Удаление через этот сервер закрыто. Исключение — мягкое удаление собственного
    комментария: запись остаётся в базе и восстановима. Всё остальное удаляет
    человек в интерфейсе.

    ## Что нужно знать заранее

    **Клиент** — пользователь с непустым персональным менеджером. Без менеджера
    это лид: он живёт в админке, а не в CRM отдела, и через этот сервер недоступен.

    **Факт продаж** — отгрузки по дате документа в 1С (`erp_created_at`), а не по
    дате создания записи: историю заказов импортировали в мае 2026, поэтому расчёт
    по дате создания даст неверный результат, который будет выглядеть правдоподобно.
    Все операции этого сервера уже считают правильно — не пересчитывайте сами.

    **Лояльностью клиента владеет 1С** и перезапишет её следующим обменом. Менять
    её отсюда нельзя и незачем. Жизненный статус (`lead`, `in_work`, `active`,
    `sleeping`, `churned`) — поле сайта, его ведёт отдел продаж, и он меняется
    операцией `client.lifecycle.change` с указанием причины.

    **Зона ответственности.** Сотрудник видит только своих клиентов, руководитель
    отдела — весь отдел. Клиент вне зоны ответственности не «запрещён», а не найден:
    подтверждать его существование сервер не будет. Передавать чужой идентификатор
    менеджера в аргументах бесполезно — видимость задаётся токеном, а не запросом.

    **Отправка писем** может быть выключена администратором. Черновик при этом
    создаётся, отправка отказывает — так и сообщите менеджеру.

    ## Отчёты и произвольные выборки

    Этот сервер отвечает за работу с клиентами. Для произвольной аналитики по
    боевой базе есть отдельный read-only сервер `/mcp/analytics`.
    MARKDOWN;

    /**
     * @var array<int, class-string<\Laravel\Mcp\Server\Tool>>
     */
    protected array $tools = [
        CrmCatalog::class,
        CrmDescribe::class,
        CrmCall::class,
        CrmClientCard::class,
        CrmContactLookup::class,
        CrmPlanProgress::class,
        CrmAddComment::class,
        CrmCreateTask::class,
    ];
}

<?php

namespace App\Mcp\Servers;

use App\Mcp\Tools\Purchasing\DefectBatch;
use App\Mcp\Tools\Purchasing\DefectBatches;
use App\Mcp\Tools\Purchasing\DefectSetPrice;
use App\Mcp\Tools\Purchasing\DefectSetPublish;
use Laravel\Mcp\Server;

/**
 * MCP-сервер закупщика: партии уценки — оценка, цена, публикация.
 *
 * Отдельный сервер, а не расширение /mcp/analytics (там запись невозможна
 * на уровне СУБД) и не /mcp/crm (токен закупщика не должен открывать CRM,
 * и наоборот). Пишущий гейт обязан иметь свои токены и свою границу.
 */
class PurchasingServer extends Server
{
    protected string $name = 'Pecado Purchasing';

    protected string $version = '1.0.0';

    protected string $instructions = <<<'MARKDOWN'
    Работа закупщика с уценкой (некондицией) Pecado: осмотр партий по фотографиям,
    назначение цены и управление видимостью на сайте.

    ## Как устроена уценка

    Партия — один вид дефекта у одного товара: описание от кладовщика, фотографии
    испорченного товара, количество. Кладовщик заводит партии на складе, закупщик
    назначает цену и включает публикацию. Партия продаётся, когда одновременно:
    назначена цена, включена публикация, партия не закрыта и остаток за вычетом
    резерва больше нуля.

    ## Порядок работы

    1. `defect-batches` с фильтром `unpriced` — партии, ждущие цену. В каждой
       партии есть ссылки на фотографии дефекта (`photos[].url`) — по ним
       оценивается степень повреждения.
    2. `defect-batch` — карточка одной партии, если нужны детали.
    3. `defect-set-price` — назначить цену. Ориентир — `reference_price.ladder`:
       лестница справочных цен товара по статусам клиентов (мода индивидуальных
       цен из 1С, первым идёт самый выгодный статус). Цена уценки должна быть
       ниже цены лучшего статуса, иначе уценка не имеет смысла; размер скидки —
       по степени повреждения с фотографий.
    4. `defect-set-publish` — включить публикацию («галочка активности»).
       Опубликованная партия сразу видна клиентам на сайте.

    ## Что нужно знать заранее

    **Операции записи выполняются от имени закупщика**, которому выдан токен:
    автор цены фиксируется в партии, все изменения журналируются. Не назначайте
    цены «на пробу» — старое значение не сохраняется.

    **Публикация без цены запрещена** на уровне сервера, а не только в интерфейсе.

    **Закрытые партии** (распроданы или списаны) не редактируются: ни цена,
    ни публикация. Их закрывает и переоткрывает склад и автоматика обмена с 1С.

    **`reference_price` может отсутствовать** — у товара нет индивидуальных цен
    в 1С. Тогда цену выбирает закупщик по своим данным; инструменты это не блокируют.

    ## Отчёты и произвольные выборки

    Этот сервер отвечает за уценку. Для произвольной аналитики по боевой базе
    есть отдельный read-only сервер `/mcp/analytics`.
    MARKDOWN;

    /**
     * @var array<int, class-string<\Laravel\Mcp\Server\Tool>>
     */
    protected array $tools = [
        DefectBatches::class,
        DefectBatch::class,
        DefectSetPrice::class,
        DefectSetPublish::class,
    ];
}

<?php

namespace App\Observers;

use App\Services\Settlements\SettlementProjector;
use Illuminate\Database\Eloquent\Model;

/**
 * Доклейка движений регистра к документу, приехавшему позже них (v16.0.0).
 *
 * Движения и документы идут разными очередями — у каждой свой connection
 * и свой набор воркеров, — поэтому движение регулярно опережает свой документ.
 * Наблюдатель закрывает эту сторону; обратную (документ раньше движения)
 * закрывает сам `SettlementProjector` при обработке `settlement.posted`.
 *
 * Один наблюдатель на три модели вместо трёх правок в обработчиках 1С: точек
 * входа у документа больше, чем кажется — обработчик события, восстановление
 * потерянного документа, ручное заведение в админке. Сшивать в каждой значило бы
 * рано или поздно одну из них пропустить.
 *
 * Срабатывает только при создании: связь проставляется один раз, а на каждом
 * сохранении документа лишний UPDATE ни к чему.
 */
class SettlementLinkObserver
{
    public function created(Model $document): void
    {
        $uuid = $document->getAttribute('uuid');

        if (! is_string($uuid) || $uuid === '') {
            return;
        }

        // Полный projectDocument, а не только линковка: опоздавшая реализация
        // должна сразу получить и колонки оплаты — её график мог приехать раньше.
        app(SettlementProjector::class)->projectDocument($uuid);
    }
}

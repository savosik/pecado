    /** Блок-обёртка с датами в шапке каждой страницы. */
    private function dates(string $effective, ?string $revised = null): array
    {
        $line = 'Дата вступления в силу: '.$effective;
        if ($revised) {
            $line .= '<br>Последняя редакция: '.$revised;
        }

        return ['type' => 'paragraph', 'data' => ['text' => $line]];
    }

    private function header(string $text, int $level = 2): array
    {
        return ['type' => 'header', 'data' => ['text' => $text, 'level' => $level]];
    }

    private function paragraph(string $text): array
    {
        return ['type' => 'paragraph', 'data' => ['text' => $text]];
    }

    /** @param array<int,string> $items */
    private function list(array $items, string $style = 'unordered'): array
    {
        return ['type' => 'list', 'data' => ['style' => $style, 'items' => $items]];
    }

    private function delimiter(): array
    {
        return ['type' => 'delimiter', 'data' => []];
    }


import { Badge, HStack, Text, VStack } from '@chakra-ui/react';
import MetricHint from '@/Crm/Components/MetricHint';

/**
 * Приоритет разбора просрочки — бейдж по матрице «сумма × возраст».
 *
 * Уровень считает сервер по абсолютным порогам: «высокий» обязан значить одно
 * и то же в любом разрезе и в любой день. Относительная шкала («100 — самая
 * тяжёлая строка отбора») этого не давала: на нашем перекосе, где на одного
 * партнёра приходится три четверти веса, все остальные — включая долг годовой
 * давности — оказывались «низкими», и метка переставала быть информацией.
 *
 * Сумма ограничивает уровень сверху: 400 ₽, висящие год, — задача на
 * взаимозачёт, а не на взыскание.
 */
export default function OverduePriority({ severity, age }) {
    if (! severity) {
        return <Text fontSize="xs" color="fg.muted">—</Text>;
    }

    return (
        <VStack align="start" gap={0}>
            <Badge size="xs" colorPalette={severity.palette} variant="subtle">
                {severity.label}
            </Badge>
            {age > 0 && (
                <Text fontSize="10px" color="fg.muted" whiteSpace="nowrap">
                    {age} дн. в среднем
                </Text>
            )}
        </VStack>
    );
}

/** Заголовок колонки — с раскрытыми порогами: метка без шкалы не читается. */
export function WeightHeader() {
    return (
        <HStack gap={1}>
            <Text fontSize="xs">Приоритет</Text>
            <MetricHint text="Приоритет разбора, а не оценка клиента. Считается по сумме и возрасту долга сразу: свыше 500 тыс ₽ дольше месяца — критично; от 10 тыс ₽ дольше трёх месяцев — высокий; мелочь до 1 тыс ₽ остаётся низкой в любом возрасте — её закрывают взаимозачётом, а не звонком. У строки берётся её срок, у строки разреза — средневзвешенный возраст долга. Сортировка «по весу» ранжирует внутри уровня: остаток, умноженный на дни ожидания." />
        </HStack>
    );
}

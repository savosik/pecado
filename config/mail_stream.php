<?php

/**
 * Поток писем: что система складывает в «Черновики» и на каких предохранителях.
 *
 * Выключено по умолчанию. Включение — это не «показать раздел», а «начать
 * складывать письма», поэтому флаг отдельный и на каждый домен свой: первичная
 * выгрузка истории из 1С не должна залить поток тысячами строк.
 */
return [
    'enabled' => (bool) env('MAIL_STREAM_ENABLED', false),

    /*
     * Поводы, по которым система собирает письма. Домен — часть ключа
     * события до точки (orders.items_updated → orders).
     */
    'domains' => [
        'orders' => (bool) env('MAIL_STREAM_ORDERS', true),
        'documents' => (bool) env('MAIL_STREAM_DOCUMENTS', true),
        'finance' => (bool) env('MAIL_STREAM_FINANCE', true),
        // Возвраты и вопросы с сайта: у них уже есть собственные письма,
        // поэтому в поток по умолчанию не идут.
        'system' => (bool) env('MAIL_STREAM_SYSTEM', false),
    ],

    /*
     * Возрастной ценз. Повод старше этого письма не порождает: бэкфилл истории
     * физически не может ничего разослать. Считается от момента появления
     * данных в системе, а не от даты документа.
     */
    'max_age_minutes' => (int) env('MAIL_STREAM_MAX_AGE_MINUTES', 180),

    /*
     * Окно склейки. 1С правит заказ построчно; серия правок с одним ключом
     * в этом окне дописывается в то же письмо, а не создаёт новое.
     */
    'coalesce_minutes' => (int) env('MAIL_STREAM_COALESCE_MINUTES', 30),

    /*
     * Сколько живёт непойманное («Мимо фильтров»). Данные не копятся, но
     * двух недель хватает, чтобы увидеть сводку и завести правило.
     */
    'unmatched_retention_days' => (int) env('MAIL_STREAM_UNMATCHED_DAYS', 14),

    /*
     * Общий рубильник автоотправки. Галочка на правиле без него не работает:
     * это последняя возможность остановить поток одной переменной.
     */
    'autosend' => (bool) env('MAIL_STREAM_AUTOSEND', false),

    /*
     * Кому приписать письмо, если у клиента нет персонального менеджера.
     * Ноль — взять первого РОП-а; письмо без автора в списке не появилось бы.
     */
    'fallback_author_id' => (int) env('MAIL_STREAM_FALLBACK_AUTHOR_ID', 0),

    /*
     * Сколько писем берётся из потока для превью правила. Превью показывает
     * реальные письма, а не абстракцию, поэтому окно ограничено.
     */
    'preview_window' => (int) env('MAIL_STREAM_PREVIEW_WINDOW', 300),

    /*
     * Как часто можно напоминать об одном и том же финансовом поводе.
     * Просрочка длится месяцами: письмо появляется на переходах, а не ежедневно.
     */
    'finance_repeat_days' => (int) env('MAIL_STREAM_FINANCE_REPEAT_DAYS', 14),

    /*
     * Предел вложения. Счёт больше этого размера письмом не уходит —
     * вместо него в тексте появляется ссылка на кабинет: почтовые серверы
     * отбивают тяжёлые письма, и клиент не получил бы ничего.
     */
    'max_attachment_bytes' => (int) env('MAIL_STREAM_MAX_ATTACHMENT_BYTES', 5 * 1024 * 1024),

    /*
     * Ступени меток для чисел: фильтр по подстроке числа не работает,
     * поэтому «просрочка:60+» — это метка, а не сравнение.
     */
    'steps' => [
        'просрочка' => [7, 30, 60, 90],
        'сумма' => [10000, 50000, 100000, 500000],
    ],
];

<?php

/*
|--------------------------------------------------------------------------
| Балл сортировки каталога «По умолчанию»
|--------------------------------------------------------------------------
|
| Команда `catalog:rebuild-sort-scores` считает каждому товару балл 0–1000
| из двух признаков продаж за скользящее окно: выручки и охвата клиентов
| (сколько разных контрагентов купили товар). Признаки нормируются в [0, 1],
| веса приводятся к сумме 1 — балл получается сопоставимым между прогонами.
|
| Наличие в балл не входит: полка «в наличии → предзаказ → остальное»
| применяется в ORDER BY по живым остаткам (App\Enums\CatalogSort).
|
*/

return [
    /*
     | Окно продаж в днях. Скользящее, а не календарный квартал: в первые дни
     | нового квартала продаж почти нет, и весь каталог обнулился бы разом.
     */
    'window_days' => (int) env('CATALOG_RANKING_WINDOW_DAYS', 90),

    /*
     | Экспертные веса признаков. Нормируются к сумме 1 при расчёте, поэтому
     | их можно задавать в любом масштабе (0.5/0.5 — то же, что 5/5).
     |
     |  revenue — выручка по реализациям за окно, в рублях;
     |  reach   — охват: число разных контрагентов, купивших товар за окно.
     */
    'weights' => [
        'revenue' => (float) env('CATALOG_RANKING_WEIGHT_REVENUE', 0.5),
        'reach' => (float) env('CATALOG_RANKING_WEIGHT_REACH', 0.5),
    ],

    /*
     | Верхняя граница балла. Балл = взвешенная сумма нормированных признаков
     | × scale, то есть лежит в [0, scale].
     */
    'scale' => (float) env('CATALOG_RANKING_SCALE', 1000),

    /*
     | Размер пачки при записи баллов в products.
     */
    'chunk' => (int) env('CATALOG_RANKING_CHUNK', 500),
];

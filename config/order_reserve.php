/**
 * Режим «Заказы в резерве» (эпик res-00, протокол v16.9.0).
 *
 * Заказ интернет-магазина создаётся в 1С с удержанием товара, окно между
 * «зарезервировал» и «подтвердил» клиент обслуживает сам. Охват задаёт 1С
 * (users.reserve_allowed — реплика их реквизита), сайт может только сужать
 * (order_reserve_overrides). Глобальный рубильник — для тихой выкатки и
 * аварийного гашения; включение в бою — отдельное решение владельцев
 * обеих сторон (зафиксировано в resolution топика №5 Agent Hub).
 */
return [
    // Глобальный рубильник режима. Пока false — radio в чекауте не показывается
    // никому и события резерва в шину не уходят, независимо от флагов партнёров.
    'enabled' => env('ORDER_RESERVE_ENABLED', false),

    // Срок резерва по умолчанию, часов. Решение владельцев обеих сторон
    // от 03.09.2026 — 24 часа; предел удержания на стороне 1С тоже 24 ч
    // (их настройка), поэтому запрошенный срок сверх предела 1С урежет
    // и вернёт фактический reserved_until.
    'hours' => (int) env('ORDER_RESERVE_HOURS', 24),

    // За сколько часов до истечения предупреждать клиента письмом
    // (orders.reserve_expiring). Письмо однократное на заказ — дедуп по
    // origin_key в MailStream.
    'expiring_notice_hours' => (int) env('ORDER_RESERVE_EXPIRING_NOTICE_HOURS', 3),

    // Канареечные испытания (Р-1…Р-6 на боевом контуре): UUID партнёров (erp_id)
    // через запятую. Пусто — режим доступен всем участникам, отмеченным 1С.
    // Непусто — только перечисленным, остальные участники резерва не видят.
    // Снимается очисткой переменной после успешных испытаний.
    'canary' => env('ORDER_RESERVE_CANARY', ''),

    // Красная зона сводки /crm/reserves: доля резервов, снятых по таймауту,
    // выше порога подсвечивает партнёра «резервирует и бросает». Только сигнал —
    // решение (сократить окно, отключить режим) принимает РОП руками.
    'expired_share_alert' => (float) env('ORDER_RESERVE_EXPIRED_SHARE_ALERT', 0.3),

    // Совместная отгрузка (протокол v16.11.0, топик №7 Agent Hub, resolution 18.09.2026):
    // клиент отмечает несколько резервов и отправляет их в отгрузку вместе — 1С оформляет
    // по группе минимальный комплект реализаций и расходных ордеров. Свой рубильник
    // поверх order_reserve.enabled: включается по отдельному решению владельцев после
    // совместных испытаний (тест-план Р-7).
    'ship_together' => [
        'enabled' => env('ORDER_SHIP_TOGETHER_ENABLED', false),

        // Страховка сайта: 1С отвечает итогом группы не позже 15 минут от первого
        // сообщения, а сайт ждёт дольше — на случай отставания потребителя. Если итог
        // так и не пришёл, заказы возвращаются в резерв с локальной причиной
        // «склад не ответил», чтобы клиент не завис навсегда в «ждём подтверждения».
        'pending_timeout_minutes' => (int) env('ORDER_SHIP_TOGETHER_PENDING_TIMEOUT_MINUTES', 60),

        // Канарейка испытаний (топик №8 Agent Hub): UUID партнёров (erp_id) через запятую.
        // Пусто — совместная отгрузка доступна всем участникам резервов; непусто — только
        // перечисленным. Снимается очисткой переменной после прогона Р-7.
        'canary' => env('ORDER_SHIP_TOGETHER_CANARY', ''),
    ],
];

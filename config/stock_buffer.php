<?php

/**
 * Страховой буфер остатков (эпик buf-00): виртуальное занижение показа
 * остатков по рисковым товарам для клиентов с галочкой stock_buffer_enabled.
 *
 * Пороги сигналов использует ночной пересчёт `stock:buffers:recompute`
 * (App\Services\Stock\StockBufferRecalculator).
 */
return [

    /*
    |--------------------------------------------------------------------------
    | Применение буфера на поверхностях (buf-04)
    |--------------------------------------------------------------------------
    | До включения флага вся инфраструктура «спит»: буфер считается и лежит
    | в product_stock_buffers, но нигде не занижает показ.
    */
    'enabled' => env('STOCK_BUFFER_ENABLED', false),

    /*
    |--------------------------------------------------------------------------
    | Сигнал «отмены строк при сборке»
    |--------------------------------------------------------------------------
    | order_items.cancelled = 1 за скользящее окно; повторная отмена — почти
    | гарантия проблемной полки. Датой заказа считается
    | COALESCE(erp_created_at, created_at) — правило бизнес-дат аналитики.
    */
    'cancellations' => [
        'window_days' => (int) env('STOCK_BUFFER_CANCELLATION_WINDOW_DAYS', 90),
        'min_events' => (int) env('STOCK_BUFFER_CANCELLATION_MIN_EVENTS', 2),
    ],

    /*
    |--------------------------------------------------------------------------
    | Сигнал «партии брака» (product_defects)
    |--------------------------------------------------------------------------
    | Открытые партии учитываются всегда, закрытые — за скользящее окно.
    */
    'defects' => [
        'closed_window_days' => (int) env('STOCK_BUFFER_DEFECT_CLOSED_WINDOW_DAYS', 180),
    ],

    /*
    |--------------------------------------------------------------------------
    | Сигнал «срок годности» (атрибут srok-godnosti-goden-do)
    |--------------------------------------------------------------------------
    | Партийных сроков в БД нет — только date-time атрибут товара. Значение
    | ближе порога (включая уже истёкшие) считается сигналом риска.
    */
    'shelf_life' => [
        'threshold_months' => (int) env('STOCK_BUFFER_SHELF_LIFE_THRESHOLD_MONTHS', 6),
    ],

    /*
    |--------------------------------------------------------------------------
    | Размер буфера
    |--------------------------------------------------------------------------
    | base = сумма весов сработавших сигналов;
    | buffer_qty = clamp(base, 0, min(max_qty, ceil(max_stock_share × остаток региона по умолчанию))).
    | Треть позиций склада лежит по 1–2 шт — поэтому для рискового SKU с таким
    | остатком буфер честно даёт ноль, а не прячет последний экземпляр.
    */
    'size' => [
        'max_qty' => (int) env('STOCK_BUFFER_MAX_QTY', 2),
        'max_stock_share' => (float) env('STOCK_BUFFER_MAX_STOCK_SHARE', 0.1),
        // Остаток ниже порога → буфер всегда 0: если единственный экземпляр
        // может быть браком, выбора у кладовщика всё равно нет, а прятать
        // последние 1–2 шт значит спрятать треть ассортимента склада.
        'min_stock' => (int) env('STOCK_BUFFER_MIN_STOCK', 3),
        'signal_weights' => [
            'cancellations' => 1,
            'defect_batches' => 1,
            'shelf_life' => 1,
        ],
    ],

];
